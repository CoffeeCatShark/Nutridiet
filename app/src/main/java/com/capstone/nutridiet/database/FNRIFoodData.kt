    // ─── SEARCH FUNCTION ──────────────────────────────
    fun search(query: String): List<FNRIFood> {
        if (query.length < 2) return emptyList()
        return foods.filter {
            it.name.contains(query, ignoreCase = true) ||
                    it.category.contains(query, ignoreCase = true)
        }.take(5)
    }

    // ─── SEARCH BY CATEGORY ───────────────────────────
    fun searchByCategory(category: String): List<FNRIFood> {
        return foods.filter {
            it.category.equals(category, ignoreCase = true)
        }
    }

    // ─── GET LOW SODIUM FOODS ─────────────────────────
    fun getLowSodiumFoods(maxSodium: Double = 200.0): List<FNRIFood> {
        return foods.filter { it.sodium <= maxSodium }
            .sortedBy { it.sodium }
    }

    // ─── GET HIGH PROTEIN FOODS ───────────────────────
    fun getHighProteinFoods(minProtein: Double = 15.0): List<FNRIFood> {
        return foods.filter { it.protein >= minProtein }
            .sortedByDescending { it.protein }
    }
